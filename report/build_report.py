def table(caption, header, rows, widths):
    tab_no[0] += 1
    para(f"Таблица {tab_no[0]} – {caption}", align=WD_ALIGN_PARAGRAPH.LEFT, indent=False, keep=True)
    t = doc.add_table(rows=1, cols=len(header))
    t.style, t.alignment = "Table Grid", WD_TABLE_ALIGNMENT.CENTER
    for cells, values, bold in [(t.rows[0].cells, header, True)] + [(None, r, False) for r in rows]:
        cells = cells or t.add_row().cells
        for c, v in zip(cells, values):
            c.text = ""
            pp = c.paragraphs[0]
            pp.paragraph_format.line_spacing = 1.0
            pp.paragraph_format.first_line_indent = Cm(0)
            pp.alignment = WD_ALIGN_PARAGRAPH.CENTER if bold else WD_ALIGN_PARAGRAPH.LEFT
            rr = pp.add_run(str(v))
            rr.font.size, rr.bold = Pt(12), bold
    for row in t.rows:  # заголовок таблицы повторяется на следующей странице
        for c, w in zip(row.cells, widths):
            c.width = Cm(w)
    trpr = t.rows[0]._tr.get_or_add_trPr()
    hdr = OxmlElement("w:tblHeader")
    hdr.set(qn("w:val"), "true")
    trpr.append(hdr)
    after_table[0] = True
    return tab_no[0]


