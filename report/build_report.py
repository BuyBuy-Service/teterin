def para(text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, bold=False, size=14, after=0, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment, pf.line_spacing, pf.space_after, pf.space_before = align, 1.5, Pt(after), Pt(0)
    pf.first_line_indent = Cm(1.25) if indent else Cm(0)
    pf.keep_with_next = keep
    if text:
        r = p.add_run(text)
        r.bold, r.font.size = bold, Pt(size)
    state["blank"] = not text
    return p


