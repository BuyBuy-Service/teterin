    pf = s.paragraph_format
    pf.space_before, pf.space_after, pf.line_spacing = Pt(0), Pt(12), 1.5
    pf.first_line_indent = Cm(1.25)
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
